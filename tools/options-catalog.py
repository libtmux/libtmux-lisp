#!/usr/bin/env python3
"""Generate native option contracts from pinned, compiled-source-checked facts."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "data/options-catalog.json"
OUTPUT = ROOT / "src/options-catalog.lisp"
CONTRACT_FIELDS = ("name", "declared_type", "value_representation", "declared_scopes",
                   "native_scopes", "flags", "array", "hook", "minimum", "maximum",
                   "choices", "separator", "pattern", "pattern_language", "unit")


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def supported_pins():
    return [cell for cell in json.loads((ROOT / "tools/tmux-sources.json").read_text())["cells"]
            if cell["purpose"] == "supported"]


def validate(data):
    if data["schema"] != "libtmux.option-contracts/1":
        raise ValueError("Unknown option-contract schema")
    if data["provenance"]["tmux_sources_sha256"] != digest(ROOT / "tools/tmux-sources.json"):
        raise ValueError("tmux source pins changed; extract and review the option catalog again")
    if [(v["version"], v["commit"]) for v in data["versions"]] != [
            (p["tmux"], p["commit"]) for p in supported_pins()]:
        raise ValueError("Option catalogs do not cover the exact supported source pins")
    for version in data["versions"]:
        if len(version["contracts"]) != len(version["source_lines"]):
            raise ValueError("Option source locations do not match contract entries")
        names = [data["contracts"][index]["name"] for index in version["contracts"]]
        if len(names) != len(set(names)):
            raise ValueError("Duplicate canonical option name")
        if any(alias["to"] not in names for alias in version["aliases"]):
            raise ValueError("Alias does not name a declared option")


def import_source(path):
    source = json.loads(path.read_text())
    if source["schema"] != "libtmux.native-options-catalog/1":
        raise ValueError("Expected the pinned tmux source extractor's catalog")
    contracts, indices, versions = [], {}, []
    for version in source["versions"]:
        ids = []
        for entry in version["options"]:
            contract = {field: entry[field] for field in CONTRACT_FIELDS}
            key = json.dumps(contract, sort_keys=True, ensure_ascii=False)
            if key not in indices:
                indices[key] = len(contracts)
                contracts.append(contract)
            ids.append(indices[key])
        versions.append({"version": version["version"], "commit": version["commit"],
                         "capabilities": version["capabilities"], "aliases": version["aliases"],
                         "contracts": ids,
                         "source_lines": [entry["source"]["line"] for entry in version["options"]]})
    data = {"schema": "libtmux.option-contracts/1", "provenance": {
        "catalog_sha256": digest(path), "tmux_sources_sha256": source["source_catalog_sha256"],
        "default_values": "omitted", "descriptions": "omitted",
        "source_file": "options-table.c"}, "contracts": contracts, "versions": versions}
    validate(data)
    INPUT.parent.mkdir(exist_ok=True)
    INPUT.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    return data


def string(value):
    # Lisp strings do not use JSON/C escape sequences for control characters.
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def keyword(value):
    if not re.fullmatch(r"[a-z][a-z0-9-]*", value):
        raise ValueError(f"Unexpected schema keyword: {value!r}")
    return ":" + value


def scalar(value):
    if value is None or value is False:
        return "nil"
    if value is True:
        return "t"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return string(value)
    if isinstance(value, list):
        return "(" + " ".join(scalar(item) for item in value) + ")"
    raise ValueError(f"Unsupported data value: {value!r}")


def render(data):
    lines = [";;; Generated by tools/options-catalog.py; edit the pinned source facts instead.",
             f";;; Input SHA256: {digest(INPUT)}", "(in-package #:libtmux.internal)", "",
             "(defparameter *option-contract-data*", "  '(" ]
    for entry in data["contracts"]:
        values = [(":name", string(entry["name"])), (":kind", keyword(entry["declared_type"])),
                  (":representation", keyword(entry["value_representation"])),
                  (":scopes", "(" + " ".join(keyword(s) for s in entry["native_scopes"]) + ")"),
                  (":flags", "(" + " ".join(keyword(s) for s in entry["flags"]) + ")")]
        for key, field in [(":array-p", "array"), (":hook-p", "hook"), (":minimum", "minimum"),
                           (":maximum", "maximum"), (":choices", "choices"), (":separator", "separator"),
                           (":pattern", "pattern"), (":pattern-language", "pattern_language"), (":unit", "unit")]:
            values.append((key, scalar(entry[field])))
        lines.append("    (" + " ".join(key + " " + value for key, value in values) + ")")
    lines += ["    ))", "", "(defparameter *option-catalog-data*", "  '("]
    for version in data["versions"]:
        capabilities = version["capabilities"]
        lines.append("    (" + string(version["version"]) + " " + string(version["commit"]))
        lines.append("     (" + " ".join(str(i) for i in version["contracts"]) + ")")
        lines.append("     (" + " ".join(str(i) for i in version["source_lines"]) + ")")
        lines.append("     (" + " ".join("(" + string(a["from"]) + " " + string(a["to"]) + ")"
                                          for a in version["aliases"]) + ")")
        lines.append("     (:formatted-p " + scalar(capabilities["show_options_format"])
                     + " :string-keys-p " + scalar(capabilities["array_key_kind"] == "integer-or-string")
                     + " :numeric-key-maximum " + scalar(capabilities["array_numeric_key_maximum"])
                     + " :user-event-hooks-p " + scalar(capabilities["user_event_hooks"]) + "))")
    lines += ["    ))", ""]
    return "\n".join(lines)


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("mode", nargs="?", choices=("check", "write", "import"), default="check")
parser.add_argument("--source-catalog", type=Path)
args = parser.parse_args()
if args.mode == "import":
    if args.source_catalog is None:
        parser.error("import requires --source-catalog")
    data = import_source(args.source_catalog)
else:
    data = json.loads(INPUT.read_text())
    validate(data)
expected = render(data)
if args.mode == "check":
    if not OUTPUT.exists() or OUTPUT.read_text() != expected:
        raise SystemExit("Stale native option catalog; run mise run catalogs")
else:
    OUTPUT.write_text(expected)
print(f"Native catalogs: {len(data['versions'])} versions, "
      f"{len(data['contracts'])} distinct contracts, "
      f"{sum(len(v['contracts']) for v in data['versions'])} entries: PASS")
